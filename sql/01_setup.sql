CREATE DATABASE IF NOT EXISTS DATAOPS_DEMO;
CREATE SCHEMA IF NOT EXISTS DATAOPS_DEMO.CORE;

USE DATABASE DATAOPS_DEMO;
USE SCHEMA CORE;

CREATE OR REPLACE TABLE CUSTOMERS (
    CUSTOMER_ID STRING,
    CUSTOMER_NAME STRING,
    REGION STRING,
    STATUS STRING
);

CREATE OR REPLACE TABLE ORDERS (
    ORDER_ID STRING,
    CUSTOMER_ID STRING,
    ORDER_TS TIMESTAMP_NTZ,
    ORDER_AMOUNT NUMBER(12,2),
    STATUS STRING
);

CREATE OR REPLACE TABLE PIPELINE_RUNS (
    RUN_ID STRING,
    PIPELINE_NAME STRING,
    START_TS TIMESTAMP_NTZ,
    END_TS TIMESTAMP_NTZ,
    STATUS STRING,
    ROWS_PROCESSED NUMBER,
    ERROR_MESSAGE STRING
);

CREATE OR REPLACE TABLE DQ_RESULTS (
    RESULT_TS TIMESTAMP_NTZ,
    RULE_ID STRING,
    RULE_NAME STRING,
    TABLE_NAME STRING,
    FAILED_ROWS NUMBER,
    TOTAL_ROWS NUMBER,
    FAILURE_RATE FLOAT,
    RUN_ID STRING
);

CREATE OR REPLACE TABLE SCHEMA_CHANGES (
    CHANGE_ID STRING,
    OBJECT_NAME STRING,
    CHANGE_TS TIMESTAMP_NTZ,
    CHANGE_TYPE STRING,
    DETAILS STRING,
    AUTHOR STRING
);

CREATE OR REPLACE TABLE DQ_INCIDENTS (
    INCIDENT_ID STRING,
    CREATED_TS TIMESTAMP_NTZ,
    TITLE STRING,
    SEVERITY STRING,
    STATUS STRING,
    ROOT_CAUSE STRING,
    CONFIDENCE FLOAT,
    AFFECTED_ROWS NUMBER,
    RECOMMENDED_ACTION STRING,
    APPROVED BOOLEAN DEFAULT FALSE
);

